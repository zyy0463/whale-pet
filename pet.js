  function frame(now) {
    raf = requestAnimationFrame(frame);
    if (!last) last = now;
    var dt = Math.min(0.05, (now - last) / 1000);
    last = now; T += dt; lastDt = dt;

    if (pokeHop !== 0) {                                        // 被戳一下的弹跳
      pokeHop *= 0.86;
      if (Math.abs(pokeHop) < 0.4) pokeHop = 0;
    }
    if (dragging !== null) {
      // v171 拖拽留尾：拖动时从尾巴后面拖一串小气泡（松手就停，气泡自己飘散）
      if (T > nextTrail && (Math.abs(vel.x) + Math.abs(vel.y)) > 1) {
        nextTrail = T + 0.05;
        bubbles.push({ x: PAD + (56 + Math.random() * 12) * S, y: PADY + (bobNow + 14 + Math.random() * 22) * S,
                       r: 0.8 + Math.random() * 1.1, vy: -(4 + Math.random() * 8),
                       vx: -vel.x * 0.35 + (Math.random() - 0.5) * 6, a: 0.45 });
      }
    }
    else if (vel.x || vel.y) {                                  // 松手后的惯性 + 撞边回弹
      pos.x += vel.x * dt * 60; pos.y += vel.y * dt * 60;
      vel.x *= 0.9; vel.y *= 0.9;
      if (Math.abs(vel.x) < 0.05) vel.x = 0;
      if (Math.abs(vel.y) < 0.05) vel.y = 0;
      var ox = pos.x, oy = pos.y;
      clampPos();
      if (ox !== pos.x) vel.x = -vel.x * 0.5;
      if (oy !== pos.y) vel.y = -vel.y * 0.5;
      savePos();
    }
    draw();
  }
