  /* ── 尺寸 / 位置 ── */
  function layout() {
    vw = window.innerWidth; vh = window.innerHeight;
    dpr = window.devicePixelRatio || 1;              // 不封顶：下面按「整数设备像素」画，画布依然很小
    var scss = scaleOverride || Math.max(1, Math.min(5, Math.round(vw * 0.08 / ((WH && WH.W) || 70))));
                                                    // 期望的 CSS 格尺寸（跟原来的观感一致）
                                                    // v220：基准仍用**鲸鱼本身的 70 列**，不是 GW(78) ——
                                                    // 网格加宽只是让画布多出空白，鲸鱼在屏上该多大还多大
                                                    // （否则同一块屏上算出来的档位会从 2× 掉成 1×，鲸鱼突然变小）
    SDEV = Math.max(1, Math.round(scss * dpr / (scaleOverride ? 1 : 2)));
                                                    // v237：她拍板「缩小一倍」→ 自动档的每格设备像素**减半**
                                                    // （她手机 3→2 ≈ 0.67 倍；桌面 2→1 正好一半）。
                                                    // 选「保清晰」这条路：像素画的命门是「一格 = 整数个设备像素」，
                                                    // 想更小就只能靠重采样（会糊）—— 所以「能小多少算多少」＝
                                                    // 设备像素减半取整。预览档（setScale）不减半，dev 面板的
                                                    // 1×/2×/4× 还是原意。
    S = SDEV / dpr;                                  // 换算回 CSS 单位（可能是小数，但落点正好是设备像素）
    var padv = Math.max(Math.round(10 * dpr), Math.round(SDEV * 6.0));
                                                    // v219 修订：难过垂尾摆动最外点要 4.93 格右留白，原来 4.4 格不够
                                                    // → 4× 实测尾尖被右缘削平（maxX 顶死在 w-1）。抬到 6.0 格。
                                                    // v220：网格本身已由 70 加到 78 列（尾尖落在格内了），这个值留着
                                                    // 不再动 —— 她日常屏 SDEV=1 时被 10*dpr 兜底，观感/位置一格不动。
    PAD = padv / dpr;                                // 气泡 / zZz 的边距，同样对齐到设备像素
    /* 头顶额外留白（v184）：只加在**头部上方**，左右和底部不动 —— 灯泡 / 气泡 / zZz 有地方待，
       而画布是底部对齐视口的、网格整体跟着往下挪，所以鲸鱼在屏幕上的位置一格都不动。
       这段留白在 layout 里一次算好 → 所有状态共用同一套尺寸，切换状态时画布不会忽大忽小。 */
    var topv = Math.round(SDEV * 16);                // 16 格（v186 由 12 格加到 16：灯高 16 格），整数设备像素
    PADY = PAD + topv / dpr;                         // 网格行 0 的画布内 y
    cv.width = SDEV * GW + padv * 2;                 // 位图尺寸 = 整数设备像素
    cv.height = SDEV * GH + padv * 2 + topv;
    cssW = cv.width / dpr; cssH = cv.height / dpr;   // CSS 尺寸反算 → 位图 1:1 落在屏幕像素上，不被缩放
    boxW = CORE_W * S + PAD * 2;                     // v220：**摆位锚点**用的盒宽 —— 按素材宽(70)算，
                                                     // 右侧那 8 列新空区不参与。这样网格 70→78 只让画布
                                                     // 往右长，鲸鱼在屏幕上的位置一格不动
    cv.style.width = cssW + "px"; cv.style.height = cssH + "px";
    ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    if (!off) { off = doc.createElement("canvas"); octx = off.getContext("2d"); }
    off.width = cv.width; off.height = cv.height;    // 尺寸一变位图自动清空（v190 离屏层，每帧整幅重画）
    octx.setTransform(dpr, 0, 0, dpr, 0, 0);
    ctx.imageSmoothingEnabled = true;                // v190：给「鲸鱼层按分数 bob 双线性平移」用（fillRect 不受影响；
                                                    // 离屏层自己全是整数格 fillRect，本来就是硬边。每帧 drawImage
                                                    // 之后立刻关回去，气泡/粒子仍是硬边）
    if (atHome) homePos();                           // v237：家在「表情按钮正上方」——键盘弹起/收起、
                                                     // 横竖屏一换就重摆一次，鲸鱼一直贴着那个按钮
    clampPos();
    applyTransform();
    if (panelEl) placePanel();                       // v237：面板开着的话，跟着鲸鱼一起挪
  }
  function clampPos() {
    pos.x = Math.max(boxW / 2 - PAD, Math.min(vw - boxW / 2 + PAD, pos.x));
    pos.y = Math.max(cssH - PAD, Math.min(vh - 2, pos.y));
  }
  function applyTransform() {
    var sn = function (v) { return Math.round(v * dpr) / dpr; };   // 画布位置也钉在设备像素上，否则整张图被重采样
    cv.style.transform = "translate3d(" + sn(pos.x - boxW / 2) + "px," + sn(pos.y - cssH) + "px,0)";
  }
