  function ensureWhale(then) {                      // 两个素材都补齐才 init（缺 whale 才拦；缺 sad 只是难过态退化成原貌）
    if (WH && SD) { GH = WH.H; then(); return; }
    var need = (WH ? 0 : 1) + (SD ? 0 : 1);
    var load = function (url, warn) {
      var s = doc.createElement("script");
      s.src = url;
      s.onload = done;
      s.onerror = function () { console.warn("[pet] " + warn + " 拉取失败：" + url); done(); };
      doc.head.appendChild(s);
    };
    function done() {
      if (--need > 0) return;
      if (!WH) WH = root.QiaomuWhale || null;
      if (!SD) SD = root.QiaomuSad || null;
      if (!WH) { console.warn("[pet] whale.js 没加载上"); return; }
      GH = WH.H; then();
    }
    if (!WH) load(WHALE_URL, "whale.js");
    if (!SD) load(SAD_URL, "whale-sad.js");
  }

