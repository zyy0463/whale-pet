  /* ── 命中判定：这个点是不是压在鲸鱼身上 ── */
  function buildMask() {
    mask = new Uint8Array(GW * GH);
    for (var y = 0; y < GH; y++) {
      var row = (WH.GRID && WH.GRID[y]) || "";
      // v220：x 要卡在**素材行长度内**（70），GW 是 78 —— 直接扫到 GW 的话，
      // 第 70~77 列 charAt 越界返回 ""（≠ "0"）会被错标成鲸鱼，右侧凭空多一块命中区
      for (var x = 0; x < GW; x++) mask[y * GW + x] = (x < row.length && row.charAt(x) !== "0") ? 1 : 0;
    }
  }
  /* 画布整块是 pointer-events:none，透明留白必须漏给壳 → 只能自己按像素判。
     逐格复算「这一格现在画在哪」，拿屏幕点去撞 —— 位移场怎么变都不会判错，
     也不会像原来那样在某个尺寸下漏掉一块（命中判定和绘制用的是同一套公式）。 */
  function hitWhale(cx, cy) {
    if (!cv || !mask) return false;
    var r = cv.getBoundingClientRect();
    var lx = cx - r.left, ly = cy - r.top;
    if (lx < 0 || ly < 0 || lx >= cssW || ly >= cssH) return false;
    for (var gy = 0; gy < GH; gy++) {
      var y0 = PADY + (bobNow + gy) * S;
      if (ly < y0 - 4 * S || ly >= y0 + S + 4 * S) continue;   // 尾鳍最多挪 3~4 格，先粗筛
      for (var gx = 0; gx < GW; gx++) {
        if (mask[gy * GW + gx] !== 1) continue;
        var x0 = PAD + (gx + cellDx(gy, gx) + tremorNowX) * S, yv = y0 + cellDy(gy, gx) * S;
                                            // v225：横向也带上抖动的位移，命中判定跟画面一格不差
        if (lx >= x0 && lx < x0 + S && ly >= yv && ly < yv + S) return true;
      }
    }
    return false;
  }

  /* ── 交互：拖 / 点 ──
     手势统一在 window 捕获层接：先判像素，不是鲸鱼就直接放行（壳拿到的是原生事件）；
     是鲸鱼才 stopPropagation + 接手。两个副作用要自己兜：
     ① 事件已经派给下面那个元素了，浏览器还会照常合成 click → 时间窗内吞掉；
     ② 触摸时壳可能开始滚动 → 拖拽期间 touchmove preventDefault。 */
  function bindDrag() {
    function clearHold() { if (holdTimer) { clearTimeout(holdTimer); holdTimer = 0; } }
    function onDown(e) {
      if (e.isPrimary === false) return;
      if (panelEl) {                                           // v237：面板开着的时候
        var tg = e.target;
        // 只判「真的点在某元素上、且那元素在面板里」——面板上的点按交给面板自己；
        // 其余（包括派到 window 上的合成事件）一律先收起，再把这一下放行给壳。
        if (tg && tg.nodeType === 1 && panelEl.contains(tg)) return;
        closePanel();
      }
      if (dragging) return;
      if (e.pointerType === "mouse" && e.button !== 0) return;
      if (!hitWhale(e.clientX, e.clientY)) return;             // 透明处：不接手
      dragging = { x: e.clientX, y: e.clientY, ox: pos.x, oy: pos.y, t: Date.now(), px: e.clientX, py: e.clientY };
      moved = 0; vel.x = vel.y = 0; holdFired = false;
      clearHold();
      /* v237：长按 2 秒**没拖动** → 头顶弹小框（选状态 / 选颜色）。一挪就取消（见 onMove）。 */
      holdTimer = setTimeout(function () {
        holdTimer = 0; holdFired = true;
        dragging = null; vel.x = vel.y = 0;                    // 开面板后这一下就不再算拖拽
        swallowClickUntil = Date.now() + 400;
        openPanel();
      }, 2000);
      swallowClickUntil = Date.now() + 600;                    // 按下这一下顺带合成的那次 click
      e.stopPropagation(); e.preventDefault();
    }
    function onMove(e) {
      if (!dragging) return;
      var dx = e.clientX - dragging.x, dy = e.clientY - dragging.y;
      moved = Math.max(moved, Math.abs(dx) + Math.abs(dy));
      if (moved >= 8) { clearHold(); atHome = false; }         // 挪了：长按作废，也不再算「在家」
      vel.x = (e.clientX - dragging.px) * 0.55;                // 记个瞬时速度，松手用
      vel.y = (e.clientY - dragging.py) * 0.55;
      dragging.px = e.clientX; dragging.py = e.clientY;
      pos.x = dragging.ox + dx; pos.y = dragging.oy + dy;
      clampPos();
      applyTransform();                                         // 立刻跟手，不等下一帧
      e.stopPropagation();
      if (e.cancelable) e.preventDefault();
    }
    function onUp(e) {
      if (!dragging) return;                                    // 长按已经开面板了：这一下不算拖/点
      clearHold();
      swallowClickUntil = Date.now() + 400;
      var quick = Date.now() - dragging.t < 260;
      dragging = null;
      if (moved < 8 && !holdFired) {                            // 没挪动 = 点了一下
        vel.x = vel.y = 0;
        poke();
        /* v237：连着点 3 下（每下间隔 < 900ms）→ 归位到「表情按钮正上方」 */
        var now = Date.now();
        tapN = (now - tapAt < 900) ? tapN + 1 : 1;
        tapAt = now;
        if (tapN >= 3) goHome();
      } else if (!quick) { vel.x = vel.y = 0; }
      holdFired = false;
      savePos();
      e.stopPropagation();
      if (e.cancelable) e.preventDefault();
    }
    function onClick(e) {                                        // 拖/点完鲸鱼，别顺带把壳的按钮点了
      if (Date.now() > swallowClickUntil) return;
      e.stopPropagation(); e.preventDefault();
    }
    function onTouchMove(e) {                                    // 拖鲸鱼时别让壳跟着滚
      if (dragging && e.cancelable) e.preventDefault();
    }
    once(window, "pointerdown", onDown, true);
    once(window, "pointermove", onMove, true);
    once(window, "pointerup", onUp, true);
    once(window, "pointercancel", onUp, true);
    once(window, "click", onClick, true);
    once(window, "touchmove", onTouchMove, { capture: true, passive: false });
  }
  function once(target, type, fn, opts) {                        // 统一登记，unmount 时一起摘
    target.addEventListener(type, fn, opts);
    teardown.push(function () { target.removeEventListener(type, fn, opts); });
  }
